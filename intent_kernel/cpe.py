"""Cognitive Planning Engine (CPE) — RFC-0009.

Transforms a structured, understood intent (StructuredIntent) into a verifiable,
dependency-aware, capability-first ExecutionPlan without executing side-effects.
"""

from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from uuid import uuid4

from intent_kernel.cdm import DialogueDecision, DialogueState
